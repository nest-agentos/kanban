import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const artifacts=process.env.KANBAN_ARTIFACTS||'_nestos/kanban/artifacts/browser';
await mkdir(artifacts,{recursive:true});
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1280,height:900}}),errors=[];
page.on('pageerror',error=>errors.push(error.message));
await page.goto(process.env.KANBAN_BROWSER_URL||'http://127.0.0.1:4179/');
const panel=page.locator('[data-panel]');
try {
    await page.waitForFunction(()=>!!window.acceptance);
    await page.locator('.kanban__desktop-create [data-action="new-item"]').click();
    await panel.locator('[name="title"]').fill('Browser task');
    await panel.locator('[name="responsibility"]').fill('Verify execution controls');
    await panel.locator('[name="acceptance"]').fill('Browser scenario passes');
    await panel.locator('[name="itemResource"]').selectOption({label:'x1'});
    await panel.locator('[data-form="item"] button:not([type=button])').click();
    await panel.locator('[data-task-phase="waiting-start"]').waitFor();
    await page.screenshot({path:artifacts+'/waiting.png'});
    const original=await page.evaluate(()=>window.acceptance.snapshot());
    const deadline=original.board.items[0].launch.startAt;
    await page.evaluate(()=>window.acceptance.tick(299999));
    assert.equal(Object.keys((await page.evaluate(()=>window.acceptance.snapshot())).dispatches.dispatches).length,0);
    await panel.locator('[data-action="task-edit"]').click();
    await panel.locator('[data-form="save-edit"] [name="title"]').fill('Reviewed browser task');
    await page.evaluate(()=>window.acceptance.tick(1));
    assert.equal(Object.keys((await page.evaluate(()=>window.acceptance.snapshot())).dispatches.dispatches).length,0);
    await panel.locator('[data-form="save-edit"] button:not([type=button])').click();
    await panel.locator('[data-task-phase="running"]').waitFor();
    let snapshot=await page.evaluate(()=>window.acceptance.snapshot());
    assert.equal(snapshot.board.items[0].launch.startAt,deadline);
    assert.equal(Object.keys(snapshot.dispatches.dispatches).length,1);
    const originalDispatch=Object.keys(snapshot.dispatches.dispatches)[0];
    await panel.locator('[data-action="task-pause"]').click();
    await panel.locator('[data-task-phase="paused"]').waitFor();
    assert.equal(await panel.locator('p').filter({hasText:/^进行中$/}).count(),0);
    await page.screenshot({path:artifacts+'/paused.png'});
    await panel.locator('[data-action="task-resume"]').click();
    await panel.locator('[data-task-phase="running"]').waitFor();
    await page.evaluate(()=>window.acceptance.publish('question','clarification','Which input should be used?'));
    await panel.locator('[data-task-phase="waiting-input"]').waitFor();
    await panel.locator('[data-form="task-reply"] [name="content"]').fill('Use the verified input');
    await panel.locator('[data-form="task-reply"] button').click();
    await panel.locator('[data-task-phase="running"]').waitFor();
    await page.evaluate(()=>window.acceptance.publish('reported-error','error','Fixture validation needs repair'));
    await panel.locator('[data-task-phase="error"]').waitFor();
    await page.evaluate(()=>window.acceptance.publish('error-resolved','resolved','Repair verified','reported-error'));
    await panel.locator('[data-task-phase="running"]').waitFor();
    await panel.locator('[data-action="task-fix"]').click();
    await page.locator('#session:not([hidden])').waitFor();
    await page.evaluate(()=>window.acceptance.proposal());
    await page.locator('#reply input').fill('完成');await page.locator('#reply button').click();
    await page.waitForFunction(()=>document.querySelector('#process').textContent.includes('Definition accepted'));
    await page.locator('#close-session').click();
    snapshot=await page.evaluate(()=>window.acceptance.snapshot());
    const fix=snapshot.board.items.find(item=>item.planning?.kind==='fix');
    assert.ok(fix);assert.deepEqual(fix.planning.dependencies,[snapshot.board.items[0].id]);assert.equal(fix.status,'backlog');
    assert.equal(Object.keys(snapshot.dispatches.dispatches).length,1);
    await page.evaluate(()=>window.acceptance.result());
    await panel.locator('[data-task-phase="review"]').waitFor();
    await panel.locator('[data-action="accept"]').click();
    await panel.locator('[data-task-phase="completed"]').waitFor();
    assert.equal(await panel.locator('[data-action="task-run"]').count(),0);
    await page.screenshot({path:artifacts+'/completed.png'});
    snapshot=await page.evaluate(()=>window.acceptance.snapshot());
    assert.equal(snapshot.dispatches.dispatches[originalDispatch].outcome,'accepted');
    assert.equal(Object.keys(snapshot.dispatches.dispatches).length,1);
    for(const [name,text] of Object.entries(await page.evaluate(()=>window.acceptance.files())))await writeFile(artifacts+'/'+name,text);
    await writeFile(artifacts+'/snapshot.json',JSON.stringify(snapshot,null,2));
    assert.deepEqual(errors,[]);console.log(JSON.stringify({result:'passed',steps:17,dispatches:1,fixTasks:1,artifacts}));
} catch(error) {await page.screenshot({path:artifacts+'/failure.png'});console.error(errors);throw error;}
finally {await browser.close();}
